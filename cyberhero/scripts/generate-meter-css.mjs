// Generates src/styles/meter.css: one rule per 5% step so the progress meter
// width can be set through a `data-value` attribute instead of an inline style
// (the platform CSP forbids `style=""`).
import { writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';

const here = dirname(fileURLToPath(import.meta.url));
const out = join(here, '..', 'src', 'styles', 'meter.css');

let css = '/* GENERATED by scripts/generate-meter-css.mjs - do not edit by hand. */\n';
for (let v = 0; v <= 100; v += 5) {
  css += `.ch-meter__fill[data-value="${v}"] { width: ${v}%; }\n`;
}
writeFileSync(out, css);
console.log(`wrote ${out}`);
